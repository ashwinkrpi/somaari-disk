"""Write somaari_disk/_build_info.py (git-ignored) with the build commit and UTC build date.

Called by packaging/linux/build_deb.py and packaging/windows/somaari-disk.spec; running from
source there is no such file and the About section shows "dev" / "unknown".
    python3 packaging/stamp_build.py <package dir>
"""

from __future__ import annotations

import os
import subprocess
import sys
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def git_commit(root: Path = ROOT) -> str | None:
    try:
        res = subprocess.run(  # noqa: S603, S607
            ["git", "rev-parse", "--short=12", "HEAD"], cwd=root, capture_output=True, text=True
        )
    except OSError:
        return None
    if res.returncode != 0:
        return None
    return res.stdout.strip() or None


def build_date() -> str:
    """UTC date; SOURCE_DATE_EPOCH (reproducible builds) wins over the clock."""
    epoch = os.environ.get("SOURCE_DATE_EPOCH")
    when = datetime.fromtimestamp(int(epoch), UTC) if epoch else datetime.now(UTC)
    return when.strftime("%Y-%m-%d")


def stamp(package_dir: Path, commit: str | None = None, date: str | None = None) -> Path:
    commit = commit or git_commit()
    target = package_dir / "_build_info.py"
    target.write_text(
        '"""Generated by packaging/stamp_build.py at build time. Not in git."""\n\n'
        f"BUILD_COMMIT = {commit[:12] if commit else None!r}\n"
        f"BUILD_DATE = {date or build_date()!r}\n",
        encoding="utf-8",
    )
    return target


if __name__ == "__main__":
    print(stamp(Path(sys.argv[1])))
